"""Companion dust maps for audited gaps in each zone's VRAM layout.

There are 16 virtual dust tiles. SLZ and MZ split them across free runs;
sprite columns split at those run boundaries without changing any pixels.
FZ has no flamethrowers/collapsing floors (objpos/fz.bin contains barriers
only), and its boss/fleeing Eggman art ends before the $3F0 dust run.
"""

from pathlib import Path

POOLS = {
    "GHZ": list(range(0x3EC, 0x3FC)),
    "LZ": list(range(0x1C6, 0x1D6)),
    "MZ": list(range(0x2EA, 0x2F2)) + list(range(0x2F8, 0x300)),
    "SLZ": list(range(0x36A, 0x374)) + list(range(0x3FC, 0x400)) + [0x7B0, 0x7B1],
    "SYZ": list(range(0x3EC, 0x3FC)),
    "SBZ": list(range(0x2A9, 0x2B0))
    + list(range(0x3FD, 0x400))
    + list(range(0x509, 0x50D))
    + [0x7B0, 0x7B1],
    "FZ": list(range(0x3F0, 0x400)),
}
SPIN = [[(-32, 4, 4, 2, 0)]] * 3 + [
    [(-24, -12, 1, 2, 0), (-32, 4, 4, 2, 2)],
    [(-24, -12, 2, 2, 0), (-32, 4, 4, 2, 4)],
    [(-32, -12, 3, 2, 0), (-32, 4, 4, 2, 6)],
    [(-32, -12, 3, 2, 0), (-32, 4, 4, 2, 6)],
]
SKID = [[(-8, -8, 2, 2, frame * 4)] for frame in range(4)]


def split_piece(pool, piece):
    """Keep contiguous columns grouped; split holes into vertical strips.

    None denotes a transparent tile that should emit no sprite. Coordinates
    remain unflipped; callers reflect these pieces for a flipped source.
    """
    x, y, w, h, start = piece
    output = []
    column = 0
    while column < w:
        tile = start + column * h
        target = pool[tile : tile + h]
        if target[0] is not None and target == list(range(target[0], target[0] + h)):
            run = 1
            while column + run < w:
                following = start + (column + run) * h
                if pool[following : following + h] != list(
                    range(target[0] + run * h, target[0] + (run + 1) * h)
                ):
                    break
                run += 1
            output.append((x + column * 8, y, run, h, target[0]))
            column += run
            continue
        row = 0
        while row < h:
            if target[row] is None:
                row += 1
                continue
            run = 1
            while row + run < h and target[row + run] == target[row] + run:
                run += 1
            output.append((x + column * 8, y + row * 8, 1, run, target[row]))
            row += run
        column += 1
    return output


def dust_outputs(root: Path) -> dict[Path, bytes]:
    out = [
        "; Generated by s1tools.sidekick_dust. Absolute tile maps, gfx base 0.",
        "Sidekick_DustMapTable:",
    ]
    for z in POOLS:
        out.append(
            f"        dc.l Map_SidekickSpinDust_{z},Map_SidekickSkidDust_{z},Sidekick_DustTiles_{z}"
        )
    for z, pool in POOLS.items():
        assert len(set(pool)) == len(pool) == 16
        out.append(f"Sidekick_DustTiles_{z}: dc.w " + ",".join(f"${t:X}" for t in pool))
        for kind, frames in [("Spin", SPIN), ("Skid", SKID)]:
            label = f"Map_Sidekick{kind}Dust_{z}"
            out.append(label + ": mappingsTable")
            for f in range(len(frames)):
                out.append(f"        mappingsTableEntry.w .frame{f}")
            for f, frame in enumerate(frames):
                out.append(f".frame{f}: spriteHeader")
                for piece in frame:
                    for x, y, w, h, tile in split_piece(pool, piece):
                        out.append(f"        spritePiece {x},{y},{w},{h},${tile:X},0,0,0,0")
                out.append(f".frame{f}_End")
            out.append("        even")
    return {root / "_inc/Sidekick Dust Assets.asm": ("\n".join(out) + "\n").encode()}
