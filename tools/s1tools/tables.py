"""Reusable tables transformations for Sonic 1 resources."""

from __future__ import annotations

import argparse

from s1tools.common import get_root

ROOT = get_root()
DEST = ROOT / "_incObj" / "Ring Loss Velocities.asm"


def expected() -> str:
    text = (ROOT / "_incObj" / "sub CalcSine.asm").read_text(encoding="utf-8")
    values = []
    for line in text.split("Sine_Data:", 1)[1].splitlines():
        line = line.split(";", 1)[0]
        if "dc.w" in line:
            values.extend(
                int(x.strip().replace("$", "0x"), 0) for x in line.split("dc.w", 1)[1].split(",")
            )
    assert len(values) == 320
    output = ["; Generated by the resource tools; do not hand-edit."]
    for water in (False, True):
        output.append("RLoss_Velocities" + ("Water" if water else "Air") + ":")
        for shift in (2, 1):
            for angle in range(136, 256, 16):
                sx, sy = (values[angle], values[angle + 64])
                if water:
                    sx >>= 1
                    sy >>= 1
                sx <<= shift
                sy <<= shift
                output.append(f"\tdc.w {sx}, {sy}, {-sx}, {sy}")
        output.extend(["\teven", ""])
    return "\n".join(output)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    text = expected()
    if args.apply:
        DEST.write_text(text, encoding="utf-8")
    elif DEST.read_text(encoding="utf-8") != text:
        raise SystemExit("Ring-loss tables differ from current sine data")
    print("All 32 air and 32 underwater velocity pairs match CalcSine and shift order")
