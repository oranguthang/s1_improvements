; Dynamic character resources, adapted from Selbi's guide:
; https://info.sonicretro.org/SCHG_How-to:Add_Extra_Characters
; ROM pointers avoid a shared RAM cache that would mix two player selections.

; Apply the saved choice to gameplay and its ending. Recorded demos and
; other presentation screens always use Sonic. Clobbers d0.
UpdateSceneCharacter:
        move.b #-1,(v_sonframenum).w ; reload art even if the new character uses the same frame
        clr.b (v_character_p1).w
        tst.w (f_demo).w
        bne.s .return
        move.b (v_gamemode).w,d0
        andi.b #$1C,d0
        cmpi.b #id_Level,d0
        beq.s .playable
        cmpi.b #id_Special,d0
        beq.s .playable
        cmpi.b #id_Ending,d0
        bne.s .return
.playable:
        move.b (v_character_selected).w,d0
        cmpi.b #Character_Count,d0
        bhs.s .return
    if (FeatureTails&FeatureKnuckles)=0
        move.l a1,-(sp)
        ext.w d0
        lea (CharacterEnabled).l,a1
        tst.b (a1,d0.w)                 ; left out of this build: stay Sonic
        movea.l (sp)+,a1                ; keeps the flags
        beq.s .return
    endif
        move.b d0,(v_character_p1).w
.return:
        rts

; d0.w = the selected solo character, Sonic if this build leaves it out.
GetSelectedCharacter:
        moveq #0,d0
        move.b (v_character_selected).w,d0
        cmpi.b #Character_Count,d0
        bhs.s .sonic
    if (FeatureTails&FeatureKnuckles)=0
        move.l a1,-(sp)
        lea (CharacterEnabled).l,a1
        tst.b (a1,d0.w)
        movea.l (sp)+,a1                ; keeps the flags
        beq.s .sonic
    endif
        rts
.sonic:
        moveq #Character_Sonic,d0
        rts

; The Special Stage results are a Sonic scene, but their continue icon shows
; the selected character: Tails' and Knuckles' go over mini Sonic's tiles
; (PLC), and their colours into slots 7-F of palette line 2, which the
; emeralds leave free (line 1 also colours them). Generated by player ui.
LoadSSResultContinueIcon:
        bsr.s GetSelectedCharacter
        tst.w d0
        beq.s .return                   ; Sonic keeps the stock icon
        lea (Pal_ContinueIconTails).l,a1
        moveq #plcid_TailsContinueIcon,d1
        cmpi.w #Character_Tails,d0
        beq.s .load
        lea (Pal_ContinueIconKnuckles).l,a1
        moveq #plcid_KnucklesContinueIcon,d1
.load:
        lea (v_palette_line_3+7*2).w,a2
        moveq #9-1,d2
.colour:
        move.w (a1)+,(a2)+
        dbf d2,.colour
        move.w d1,d0
        jmp (AddPLC).l
.return:
        rts

; d0.w = slot (0/1), d1.b = form (0 normal/nonzero Super), output a3.
; Invalid slots/IDs fall back to Sonic. Preserve all other registers and CCR.
GetCharacterAssets:
        move.w sr,-(sp)
        movem.l d0-d2,-(sp)
        cmpi.w #1,d0
        bls.s .slot
        moveq #0,d0
.slot:
        lea (v_character_p1).w,a3
        moveq #0,d2
        move.b (a3,d0.w),d2
        cmpi.w #Character_Count,d2
        blo.s .valid
        moveq #Character_Sonic,d2
.valid:
        lsl.w #3,d2
        tst.b d1
        beq.s .normal
        addq.w #4,d2
.normal:
        lea (CharacterAssets).l,a3
        movea.l (a3,d2.w),a3
        movem.l (sp)+,d0-d2
        move.w (sp)+,ccr
        rts

GetPlayer1Assets_Normal:
        move.w sr,-(sp)
        movem.l d0-d1,-(sp)
        moveq #0,d0
        moveq #0,d1
        bra.s GetPlayer1Assets_Finish
GetPlayer1Assets_Super:
        move.w sr,-(sp)
        movem.l d0-d1,-(sp)
        moveq #0,d0
        moveq #1,d1
        bra.s GetPlayer1Assets_Finish
GetPlayer1Assets_Current:
        move.w sr,-(sp)
        movem.l d0-d1,-(sp)
        moveq #0,d0
        move.b (v_supersonic).w,d1
GetPlayer1Assets_Finish:
        bsr.w GetCharacterAssets
        movem.l (sp)+,d0-d1
        move.w (sp)+,ccr
        rts

; Output d0.w = normal palette ID. Preserve address registers.
GetPlayerPaletteID:
        move.l a3,-(sp)
        bsr.w GetPlayer1Assets_Normal
        moveq #0,d0
        move.b CharacterAsset_PaletteID(a3),d0
        movea.l (sp)+,a3
        rts

; Keep Sonic's per-act palette overrides; other characters own their palettes.
; Input a2 = act header. Output d0.w = normal underwater palette ID.
GetPlayerWaterPaletteID:
        moveq #0,d0
        move.b LevelHeader_WaterSonic(a2),d0
        cmpi.b #Character_Sonic,(v_character_p1).w
        beq.s .return
        cmpi.b #Character_Count,(v_character_p1).w
        bhs.s .return
        move.l a3,-(sp)
        bsr.w GetPlayer1Assets_Normal
        move.b CharacterAsset_WaterID(a3),d0
        cmpi.w #id_LZ_act4,(v_zone_act).w
        bne.s .restore
        move.b CharacterAsset_SBZ3ID(a3),d0
.restore:
        movea.l (sp)+,a3
.return:
        rts

LoadPlayerHUD:
        move.l a3,-(sp)
        bsr.w GetPlayer1Assets_Normal
        moveq #0,d0
        move.b CharacterAsset_HUD(a3),d0
        movea.l (sp)+,a3
        jmp (AddPLC).l

; Ending art and HUD are loaded immediately before the initial fade-in.
; Keep the shared scenery PLC independent of the selected character.
LoadEndingCharacterArt:
        bsr.s GetEndingCharacterIndex
        lea EndingCharacterPLCs(pc),a1
        move.w (a1,d0.w),d0
        jmp (QuickPLC).l

GetEndingCharacterMap:
        bsr.s GetEndingCharacterIndex
        add.w d0,d0
        lea EndingCharacterMaps(pc),a1
        move.l (a1,d0.w),obMap(a0)
        move.w #ArtTile_Ending_Sonic,obGfx(a0)
        rts

GetEndingCharacterIndex:
        moveq #0,d0
        move.b (v_character_p1).w,d0
        cmpi.w #Character_Count,d0
        blo.s .valid
        moveq #Character_Sonic,d0
.valid:
        add.w d0,d0
        rts

EndingCharacterPLCs:
        dc.w plcid_SonicEnding,plcid_TailsEnding,plcid_KnucklesEnding
EndingCharacterMaps:
        dc.l Map_ESon,Map_ETails,Map_EKnuckles

; Queue the shared monitor sheet followed by the selected 1UP portrait.
LoadPlayerMonitors:
        moveq #plcid_Main2,d0
        cmpi.b #Character_Tails,(v_character_p1).w
        bne.s .knuckles
        moveq #plcid_TailsMonitors,d0
        bra.s .queue
.knuckles:
        cmpi.b #Character_Knuckles,(v_character_p1).w
        bne.s .queue
        moveq #plcid_KnucklesMonitors,d0
.queue:
        jmp (AddPLC).l

; Output d0.w = the active player's signpost PLC, preserving other registers.
GetPlayerSignpostPLC:
        moveq #plcid_Signpost,d0
        cmpi.b #Character_Tails,(v_character_p1).w
        bne.s .knuckles
        moveq #plcid_TailsSignpost,d0
        rts
.knuckles:
        cmpi.b #Character_Knuckles,(v_character_p1).w
        bne.s .return
        moveq #plcid_KnucklesSignpost,d0
.return:
        rts

; Screens with their own palettes retain the shared colours and tint only fur.
ApplyPlayerFadeColours:
        cmpi.b #Character_Sonic,(v_character_p1).w
        beq.s .return
        movem.l a1/a3,-(sp)
        bsr.w GetPlayer1Assets_Normal
        movea.l CharacterAsset_Palette(a3),a1
        move.l 4(a1),(v_palette_fading+4).w
        move.l 8(a1),(v_palette_fading+8).w
        movem.l (sp)+,a1/a3
.return:
        rts

; Special Stage player frames per character: mappings, DPLC and art, or
; 0 to use the character's own. Palette line 0 keeps the stage's blue blocks,
; so these frames draw their details with line 0 and their fur with the
; character's block line (orange line 1 for Tails, red line 2 for Knuckles);
; s1tools.special_stage generates them from the rolling frames.
SSPlayer_Assets:
        dc.l 0,0,0
        dc.l Map_TailsSS,TailsSSDynPLC,Art_TailsSS
        dc.l Map_KnucklesSS,KnucklesSSDynPLC,Art_KnucklesSS
SSPlayer_Assets_End:
        if (SSPlayer_Assets_End-SSPlayer_Assets)<>Character_Count*12
        fatal "Add Special Stage player frames for each character."
        endif

; Output a1 = this character's SSPlayer_Assets entry, Z set if it has none.
GetSSPlayerAssets:
        moveq #0,d1
        move.b (v_character_p1).w,d1
        mulu.w #12,d1
        lea SSPlayer_Assets(pc),a1
        adda.w d1,a1
        tst.l (a1)
        rts

; Nonzero for each character that this build lets the player select.
    if (FeatureTails&FeatureKnuckles)=0
CharacterEnabled:
        dc.b 1,FeatureTails,FeatureKnuckles
CharacterEnabled_End:
        if (CharacterEnabled_End-CharacterEnabled)<>Character_Count
        fatal "Add an enable flag for each character."
        endif
        even
    endif

CharacterAssets:
        dc.l CharacterAssets_Sonic,CharacterAssets_SuperSonic
        dc.l CharacterAssets_Tails,CharacterAssets_SuperTails
        dc.l CharacterAssets_Knuckles,CharacterAssets_SuperKnuckles
CharacterAssets_End:
        if (CharacterAssets_End-CharacterAssets)<>Character_Count*8
        fatal "Character table count mismatch"
        endif
CharacterAssets_Sonic:
        dc.l Art_Sonic,Map_Sonic,SonicDynPLC,Ani_Sonic
        dc.l Pal_Sonic,Pal_LZSonWater,Pal_SBZ3SonWat
        dc.l Pal_SuperSonicCycle,Pal_SuperSonicCycle_LZWater,Pal_SuperSonicCycle_SBZ3Water
        dc.l SonAni_Run,SonAni_Walk,SonAni_Roll,SonAni_Roll2,SonAni_Push,SonAni_Figure8
        dc.l Art_Sonic
        dc.b 0,0,palid_Sonic,palid_LZSonWater,palid_SBZ3SonWat,plcid_PlayerHUD
        dc.b 7,7,$78,6
CharacterAssets_SuperSonic:
        dc.l Art_SuperSonic,Map_SuperSonic,SuperSonicDynPLC,Ani_SuperSonic
        dc.l Pal_SuperSonic,Pal_SuperSonicWater,Pal_SuperSonicSBZ3Water
        dc.l Pal_SuperSonicCycle,Pal_SuperSonicCycle_LZWater,Pal_SuperSonicCycle_SBZ3Water
        dc.l SupSonAni_Run,SupSonAni_Walk,SupSonAni_Roll,SupSonAni_Roll2,SupSonAni_Push,SonAni_Figure8
        dc.l Art_Sonic
        dc.b fr_SuperSpringTwirl1,fr_SuperAirPosesEnd
        dc.b palid_SuperSonic,palid_SuperSonicWater,palid_SuperSonicSBZ3Water,plcid_PlayerHUD
        dc.b 7,7,$78,8                 ; ten steady frames, eight game frames each
CharacterAssets_RecordsEnd:
        if (CharacterAssets_SuperSonic-CharacterAssets_Sonic)<>CharacterAsset_Size
        fatal "Normal character descriptor size mismatch"
        endif
        if (CharacterAssets_RecordsEnd-CharacterAssets_SuperSonic)<>CharacterAsset_Size
        fatal "Super character descriptor size mismatch"
        endif
